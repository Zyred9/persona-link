const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const pending = [], navigations = [], toasts = [], previews = [];
let definition, componentDefinition;
const wx = { previewImage(value) { previews.push(value); }, navigateTo({ url }) { navigations.push(url); }, showToast({ title }) { toasts.push(title); } };
const request = (options) => new Promise((resolve, reject) => pending.push({ ...options, resolve, reject }));
vm.runInNewContext(read('subpackages/account/pages/review/index.js'), { Page(value) { definition = value; }, require: () => ({ authenticatedRequestData: request }), wx });
vm.runInNewContext(read('components/account-center/index.js'), { Component(value) { componentDefinition = value; }, require: () => ({ authenticatedRequestData: request, resolvePreviewUrl: (url) => url ? `https://example.com${url}` : '' }), wx });
const page = (options) => {
  const instance = { ...definition, data: { ...definition.data }, setData(values, callback) { Object.assign(this.data, values); if (callback) callback(); } };
  instance.onLoad(options);
  return instance;
};
const question = (id, selected = []) => ({ questionId: id, questionText: `历史题目${id}`, selectedOptionIds: selected,
  options: [{ optionId: 1, optionCode: 'A', optionText: '选项A' }, { optionId: 2, optionCode: 'B', optionText: '选项B' }] });
const self = { key: 'self', label: '我的作答', title: '历史题型', questions: [question(20, ['2']), question(10, [1, 2])] };
const partner = { key: 'partner', label: '对方的作答', title: '历史题型', questions: [question(20, [1]), question(10)] };
const event = (dataset) => ({ currentTarget: { dataset } });
async function run() {
  const review = page({ answerSessionId: '12' });
  let load = review.loadReview();
  assert.equal(pending.at(-1).url, '/api/miniapp/assessments/12/review');
  assert.equal(pending.at(-1).sessionBound, true);
  pending.at(-1).resolve({ participants: [self] }); await load;
  assert.equal(review.data.state, 'ready');
  assert.equal(review.data.question.questionId, 20, '保持历史顺序');
  assert.equal(review.data.question.options[1].selected, true);
  assert.equal(review.data.question.options[0].selected, false);
  assert.equal(review.data.questionSlideClass, '', '首屏不播放切题动画');
  review.previousQuestion(); assert.equal(review.data.questionIndex, 0);
  review.nextQuestion(); assert.equal(review.data.questionIndex, 1);
  assert.equal(review.data.questionSlideClass, 'review-panel--next', '下一题从右侧滑入');
  assert.ok(review.data.question.options.every((option) => option.selected), '多选全部标记');
  review.nextQuestion(); assert.equal(review.data.questionIndex, 1);
  review.previousQuestion(); assert.equal(review.data.questionIndex, 0);
  assert.equal(review.data.questionSlideClass, 'review-panel--prev', '上一题从左侧滑入');
  review.switchParticipant(event({ key: 'partner' })); assert.equal(review.data.activeKey, 'self');

  const pair = page({ pairSessionId: '99' });
  load = pair.loadReview(); assert.equal(pending.at(-1).url, '/api/miniapp/pairs/99/review');
  pending.at(-1).resolve({ participants: [self] }); await load;
  assert.equal(pair.data.participants.length, 1);
  load = pair.loadReview(); pending.at(-1).resolve({ participants: [self, partner] }); await load;
  assert.equal(pair.data.participants.length, 2, '刷新后出现对方Tab');
  pair.handleReviewTouchStart({ touches: [{ clientX: 240, clientY: 120 }] });
  pair.handleReviewTouchEnd({ changedTouches: [{ clientX: 120, clientY: 128 }] });
  assert.equal(pair.data.questionIndex, 1, '左滑必须进入下一题');
  pair.handleReviewTouchStart({ touches: [{ clientX: 120, clientY: 120 }] });
  pair.handleReviewTouchEnd({ changedTouches: [{ clientX: 260, clientY: 132 }] });
  assert.equal(pair.data.questionIndex, 0, '右滑必须返回上一题');
  pair.handleReviewTouchStart({ touches: [{ clientX: 240, clientY: 120 }] });
  pair.handleReviewTouchEnd({ changedTouches: [{ clientX: 200, clientY: 320 }] });
  assert.equal(pair.data.questionIndex, 0, '纵向手势不得切换题目');
  pair.nextQuestion(); pair.switchParticipant(event({ key: 'partner' }));
  assert.equal(pair.data.questionIndex, 0); assert.equal(pair.data.question.options[0].selected, true);
  pair.nextQuestion(); assert.equal(pair.data.question.unanswered, true);
  pair.switchParticipant(event({ key: 'self' })); assert.equal(pair.data.question.options[1].selected, true);

  const stale = pair.loadReview(); const old = pending.at(-1);
  const fresh = pair.loadReview(); pending.at(-1).resolve({ participants: [self] }); await fresh;
  old.resolve({ participants: [self, partner] }); await stale;
  assert.equal(pair.data.participants.length, 1, '旧响应不得覆盖刷新');
  load = pair.loadReview(); pair.onHide(); pending.at(-1).resolve({ participants: [self, partner] }); await load;
  assert.equal(pair.data.participants.length, 0, '离开后不回写敏感作答');
  pair.onShow(); pending.at(-1).reject(new Error('历史内容已删除')); await new Promise(setImmediate);
  assert.equal(pair.data.state, 'error'); assert.match(pair.data.error, /已删除/);
  load = pair.loadReview(); pending.at(-1).resolve({ participants: [] }); await load;
  assert.equal(pair.data.state, 'error');
  const invalid = page({}); await invalid.loadReview(); assert.equal(invalid.data.state, 'error');

  const account = { ...componentDefinition.methods, componentAttached: true, data: { currentView: 'history' } };
  account.previewCover(event({ url: '/cover.png' }));
  assert.equal(previews[0].current, 'https://example.com/cover.png');
  assert.equal(previews[0].urls[0], previews[0].current);
  assert.equal(navigations.length, 0, '预览不能导航');
  account.previewCover(event({})); assert.equal(previews.length, 1);
  account.handleRecordTap(event({ answerSessionId: '12' }));
  assert.equal(navigations.at(-1), '/subpackages/account/pages/review/index?answerSessionId=12');
  account.handlePairTap(event({ pairSessionId: '99' }));
  assert.equal(navigations.at(-1), '/subpackages/account/pages/review/index?pairSessionId=99');
  account.openRecordResult(event({ reportId: '42' }));
  assert.equal(navigations.at(-1), '/subpackages/test/pages/result/index?reportId=42');
  let result = account.openPairResult(event({ pairSessionId: '99' }));
  const navigationCount = navigations.length;
  pending.at(-1).resolve({ pairStatus: 2 }); await result;
  assert.equal(navigations.length, navigationCount, '等待对方完成时不跳转');
  assert.equal(toasts.at(-1), '等待对方完成作答');
  result = account.openPairResult(event({ pairSessionId: '99' }));
  pending.at(-1).resolve({ pairStatus: 3 }); await result;
  assert.equal(toasts.at(-1), '报告生成中，请稍后查看', '报告生成中保持提示');
  result = account.openPairResult(event({ pairSessionId: '99' }));
  pending.at(-1).resolve({ pairStatus: 4 }); await result;
  assert.equal(navigations.at(-1), '/subpackages/pair/pages/result/index?pairSessionId=99');
  const requestCount = pending.length;
  await account.openPairResult(event({ pairSessionId: '99', reportReady: true }));
  assert.equal(pending.length, requestCount, '已生成报告直接导航');
  result = account.openPairResult(event({ pairSessionId: '99' }));
  const late = pending.at(-1);
  account.clearFeedbackRedirect = () => {};
  componentDefinition.pageLifetimes.hide.call(account);
  account.pageHidden = false;
  const beforeLate = navigations.length;
  late.resolve({ pairStatus: 4 }); await result;
  assert.equal(navigations.length, beforeLate, '离开再返回后旧请求不自动跳转');
  const template = read('components/account-center/index.wxml');
  assert.match(template, /catchtap="openRecordResult"/); assert.match(template, /catchtap="openPairResult"/);
  assert.equal((template.match(/data-url="\{\{item.coverUrl\}\}" catchtap="previewCover"/g) || []).length, 2, '单人双人封面均拦截冒泡预览');
  const reviewTemplate = read('subpackages/account/pages/review/index.wxml');
  assert.match(reviewTemplate, /participants.length > 1/);
  assert.match(reviewTemplate, /disabled="\{\{questionIndex === 0\}\}"/);
  assert.match(reviewTemplate, /disabled="\{\{questionIndex \+ 1 >= questionCount\}\}"/);
  assert.match(reviewTemplate, /bindtouchstart="handleReviewTouchStart"/);
  assert.match(reviewTemplate, /bindtouchend="handleReviewTouchEnd"/);
  assert.match(reviewTemplate, /class="review-panel \{\{questionSlideClass\}\}"/);
  const reviewStyle = read('subpackages/account/pages/review/index.wxss');
  assert.match(reviewStyle, /@keyframes review-panel-in-right/);
  assert.match(reviewStyle, /@keyframes review-panel-in-left/);
  const reviewConfig = JSON.parse(read('subpackages/account/pages/review/index.json'));
  assert.equal(reviewConfig.enablePullDownRefresh, false, '作答回顾不允许下拉刷新');
  assert.equal(reviewConfig.disableScroll, true, '作答回顾不允许纵向滚动');
  assert.doesNotMatch(read('subpackages/account/pages/review/index.js'), /method:\s*['"](?:POST|PUT|DELETE)/);
  assert.doesNotMatch(read('subpackages/account/pages/review/index.js'), /onPullDownRefresh/);
  console.log('ANSWER_REVIEW_CHECK_OK history-order/single/pair-tabs/multiselect/readonly/bounds/swipe/slide-animation/no-pull-down/no-scroll/stale/error/navigation');
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
